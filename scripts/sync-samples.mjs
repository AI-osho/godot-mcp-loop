#!/usr/bin/env node
// Generates five legacy standalone deliveries and the integrated tower-defense example.
// Marble keeps its existing opposite-direction generator and --check compatibility.
import { existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, writeFileSync, chmodSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
if (process.argv.slice(2).some((arg) => arg !== "--check")) throw new Error("Only --check is supported.");
const skipped = new Set([".git", ".godot", ".DS_Store", "node_modules", "qa"]);
const specs = [
  { name: "platformer", title: "Minimal Platformer", entry: "main.tscn", inputs: ["move_left", "move_right", "jump"] },
  { name: "blocks", title: "Falling Blocks", entry: "blocks.tscn", inputs: [] },
  { name: "shooter", title: "Vertical Shooter", entry: "shooter.tscn", inputs: ["shooter_left", "shooter_right", "shooter_up", "shooter_down", "shooter_fire", "shooter_start"] },
  { name: "action", title: "Side-scroller", entry: "action_game.tscn", inputs: ["action_left", "action_right", "action_jump", "action_start"] },
  { name: "rpg", title: "Luka of the Star Sword", entry: "main.tscn", inputs: ["rpg_up", "rpg_down", "rpg_left", "rpg_right", "rpg_confirm", "rpg_cancel"] },
];

function safe(path) {
  const rel = relative(repo, path);
  if (rel === ".." || rel.startsWith("../") || resolve(repo, rel) !== path) throw new Error("Path escaped the repository.");
  let current = repo;
  for (const part of rel.split("/").filter(Boolean)) {
    current = join(current, part);
    if (!existsSync(current)) {
      // lstat also notices dangling links that existsSync follows and misses.
      try { if (lstatSync(current).isSymbolicLink()) throw new Error("Refusing linked generation path."); }
      catch (error) { if (error.code !== "ENOENT") throw error; }
      continue;
    }
    const stat = lstatSync(current);
    if (stat.isSymbolicLink() || (stat.isFile() && stat.nlink > 1)) throw new Error("Refusing linked generation path.");
  }
}

function files(root, path = root) {
  safe(path);
  const out = [];
  for (const entry of readdirSync(path, { withFileTypes: true })) {
    if (skipped.has(entry.name)) continue;
    const full = join(path, entry.name);
    safe(full);
    if (entry.isDirectory()) out.push(...files(root, full));
    else if (entry.isFile()) out.push(full);
    else throw new Error("Only regular sample files are supported.");
  }
  return out.sort();
}

const inputText = readFileSync(join(repo, "project.godot"), "utf8").split("[input]\n")[1];
if (!inputText) throw new Error("Missing authoritative input map.");
const inputs = new Map([...inputText.matchAll(/^([a-z][a-z0-9_]*)=\{\n.*?^\}/gms)].map((match) => [match[1], match[0].trim()]));

function project(spec) {
  let text = "; Generated by scripts/sync-samples.mjs. Edit the authoritative examples and project input map.\nconfig_version=5\n\n[application]\n";
  text += `config/name=${JSON.stringify(spec.title)}\nrun/main_scene="res://examples/${spec.name}/${spec.entry}"\nconfig/features=PackedStringArray("4.7")\n`;
  if (spec.inputs.length) text += "\n[input]\n\n" + spec.inputs.map((name) => {
    if (!inputs.has(name)) throw new Error("Missing required sample input action.");
    return inputs.get(name);
  }).join("\n") + "\n";
  return text + '\n[rendering]\nrenderer/rendering_method="gl_compatibility"\n';
}

// Validate every destination before writing any group; unknown files are retained and refused, never deleted.
const plans = specs.map((spec) => {
  const source = join(repo, "examples", spec.name);
  const target = join(repo, "samples", spec.name);
  safe(source); safe(target);
  const expected = new Map();
  for (const full of files(source)) {
    expected.set(join("examples", spec.name, relative(source, full)), { data: readFileSync(full), mode: lstatSync(full).mode & 0o777 });
  }
  expected.set("project.godot", { data: Buffer.from(project(spec)), mode: 0o644 });
  expected.set("LICENSE", { data: readFileSync(join(repo, "LICENSE")), mode: 0o644 });
  // Player-facing guides are also placed at the standalone root; their authority stays with the example.
  for (const doc of ["README.md", "PLAY.ja.md", "UPGRADING.md", "DESIGN.md"]) {
    const full = join(source, doc);
    safe(full);
    expected.set(doc, { data: readFileSync(full), mode: lstatSync(full).mode & 0o777 });
  }
  if (existsSync(target)) {
    for (const full of files(target)) {
      if (!expected.has(relative(target, full))) throw new Error(`Unmanaged file retained in samples/${spec.name}; reconcile it explicitly.`);
    }
  }
  for (const rel of expected.keys()) safe(join(target, rel));
  return { spec, target, expected };
});
// The new sample is authoritative in samples/. Import sidecars are regenerated for the new resource URIs.
const towerSource = join(repo, "samples", "tower-defense");
const towerTarget = join(repo, "examples", "tower-defense");
safe(towerSource); safe(towerTarget);
const towerExpected = new Map();
for (const full of files(towerSource)) {
  const rel = relative(towerSource, full);
  if (rel === "project.godot" || rel.endsWith(".import")) continue;
  let data = readFileSync(full);
  if (/\.(gd|tscn|json|md)$/.test(rel)) {
    data = Buffer.from(data.toString("utf8").replaceAll("res://", "res://examples/tower-defense/"));
    // Fresh imports receive new texture UIDs. Keep the relocated path rather than a stale standalone UID.
    if (rel.endsWith(".tscn")) data = Buffer.from(data.toString("utf8").replace(/^(\[ext_resource type="Texture2D") uid="uid:\/\/[^"]+"/gm, "$1"));
    if (rel.endsWith(".md")) data = Buffer.concat([Buffer.from("> Generated repository copy. Edit samples/tower-defense, then run scripts/sync-samples.mjs.\n\n"), data]);
  }
  towerExpected.set(rel, { data, mode: lstatSync(full).mode & 0o777 });
}
if (existsSync(towerTarget)) {
  for (const full of files(towerTarget)) {
    const rel = relative(towerTarget, full);
    const generatedImport = /\.(png|wav)\.import$/.test(rel) && towerExpected.has(rel.slice(0, -7));
    if (!towerExpected.has(rel) && !generatedImport) throw new Error("Unmanaged file retained in examples/tower-defense; reconcile it explicitly.");
  }
}
for (const rel of towerExpected.keys()) safe(join(towerTarget, rel));
plans.push({ spec: { name: "tower-defense" }, target: towerTarget, expected: towerExpected });

let changed = 0;
for (const { spec, target, expected } of plans) {
  for (const [rel, item] of expected) {
    const dest = join(target, rel);
    if (existsSync(dest) && readFileSync(dest).equals(item.data) && (lstatSync(dest).mode & 0o777) === item.mode) continue;
    changed++;
    if (check) console.log(`out of date: ${relative(repo, dest)}`);
    else {
      mkdirSync(dirname(dest), { recursive: true });
      writeFileSync(dest, item.data);
      chmodSync(dest, item.mode);
    }
  }
}
if (check && changed) process.exitCode = 1;
console.log(check ? `Checked ${plans.length} sample generations; ${changed} difference(s).` : `Generated ${plans.length} sample generations; ${changed} updated file(s).`);
